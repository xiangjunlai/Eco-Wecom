#!/usr/bin/env bash
# ============================================================
# 平台铁律校验脚本
# 用途：检查 Skill 全部 .md 文件中，是否存在「非禁止语境」的友商平台提及。
# 友商平台 = 钉钉 / 飞书 / 宜搭 / Lark / Airtable / 简道云 / 明道云 等。
#
# 允许出现的两种合法语境：
#   1) 禁止性语境：包含「禁止/绝不/绝对/友商/❌/⚠️/迁移/不写」等关键词的行。
#   2) 平台铁律对照表：以「| 企业微信」开头的表格行（左✅企业微信，右❌友商）。
#
# 退出码：0 = 干净；1 = 发现违规提及。
# 用法：bash scripts/check_platform_lock.sh
# ============================================================
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

PATTERN='钉钉|飞书|宜搭|Lark|Airtable|简道云|明道云'
# 禁止性语境关键词（出现这些词说明是在“禁止/对比”，属合法）
SAFE_CTX='禁止|绝不|绝对|不接受|不可改|友商|❌|⚠️|迁移|含糊|不写|不能出现|不要出现'

violations=$(grep -rnE "$PATTERN" --include="*.md" . 2>/dev/null \
  | grep -vE "$SAFE_CTX" \
  | grep -vE '\|\s*企业微信' || true)

echo "=== 平台铁律校验：扫描全部 .md 文件 ==="
if [ -n "$violations" ]; then
  echo ">>> ⚠️ 发现非禁止语境的友商平台提及，请修复："
  echo "$violations"
  exit 1
else
  echo ">>> ✅ 完全干净：所有友商提及均位于禁止语境或平台铁律对照表的 ❌ 禁止列。"
  exit 0
fi
