WX_BLUE = "1677FF"      # 企业微信蓝（锁死主色）
HEAD_BG = "1677FF"      # 表头底色
ZEBRA   = "F1F8FF"      # 浅蓝斑马行

def set_cell_bg(cell, hex_color):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hex_color)
    tcPr.append(shd)

def set_cell_text(cell, text, *, bold=False, color=None, size=10, align='left', white=False):
    cell.text = ""
    p = cell.paragraphs[0]
    p.alignment = {'left':WD_ALIGN_PARAGRAPH.LEFT,'center':WD_ALIGN_PARAGRAPH.CENTER}[align]
    run = p.add_run(text)
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = '微软雅黑'
    run._element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
    if white:
        run.font.color.rgb = RGBColor(0xFF,0xFF,0xFF)
    elif color:
        run.font.color.rgb = RGBColor.from_string(color)

def add_heading(doc, text, level=1):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.bold = True
    run.font.name = '微软雅黑'
    run._element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
    if level == 1:
        run.font.size = Pt(15)
        run.font.color.rgb = RGBColor.from_string(WX_BLUE)
        # 底部蓝线
        pPr = p._p.get_or_add_pPr()
        pbdr = OxmlElement('w:pBdr')
        bottom = OxmlElement('w:bottom')
        bottom.set(qn('w:val'),'single'); bottom.set(qn('w:sz'),'12')
        bottom.set(qn('w:space'),'4'); bottom.set(qn('w:color'),WX_BLUE)
        pbdr.append(bottom); pPr.append(pbdr)
        p.space_before = Pt(10); p.space_after = Pt(6)
    else:
        run.font.size = Pt(12)
        run.font.color.rgb = RGBColor.from_string("1E477D")
    return p

def make_table(doc, headers, rows, widths=None):
    """headers: 表头列表；rows: 二维内容(占位符)；返回 table"""
    ncol = len(headers)
    t = doc.add_table(rows=1, cols=ncol)
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    # 表头
    for j, h in enumerate(headers):
        c = t.rows[0].cells[j]
        set_cell_bg(c, HEAD_BG)
        set_cell_text(c, h, bold=True, white=True, size=10, align='center')
    # 内容行
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for j, val in enumerate(row):
            set_cell_text(cells[j], val, size=10)
            if ri % 2 == 1:
                set_cell_bg(cells[j], ZEBRA)
    if widths:
        for j, w in enumerate(widths):
            for r in t.rows:
                r.cells[j].width = Cm(w)
    return t

def ph(*cols):
    """快捷生成一行占位符"""
    return list(cols)

